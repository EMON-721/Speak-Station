import assert from 'node:assert/strict';
import {loadTs} from './ts-loader.mjs';
const {eligibility,PRACTICE_INTERVAL_MS,PRACTICE_DAY_MS,TEST_INTERVAL_MS,MAX_PRACTICES_PER_24H}=loadTs('app/lib/session-policy.ts');
const start='2026-11-01T00:00:00.000Z',base=Date.parse(start);
const iso=offset=>new Date(base+offset).toISOString();
const modules=[{module:'daily:1',completed_at:iso(-86400000)},{module:'daily:2',completed_at:iso(-2*86400000)}];
const records=(times,category='practice')=>times.map(t=>({category,started_at:iso(t)}));
const p=(sessions,time)=>eligibility('practice',sessions,modules,new Date(iso(time)));
const t=(sessions,mod,time)=>eligibility('test',sessions,mod,new Date(iso(time)));
assert.equal(MAX_PRACTICES_PER_24H,3);
assert(p([],0).allowed);
assert(!p(records([0]),PRACTICE_INTERVAL_MS-1000).allowed,'five hours 59m 59s must be locked');
assert(p(records([0]),PRACTICE_INTERVAL_MS).allowed,'exact six hours opens one practice');
assert(p(records([0,6].map(h=>h*3600000)),12*3600000).allowed,'third practice starts at six-hour boundary');
assert(!p(records([0,6,12].map(h=>h*3600000)),18*3600000).allowed,'fourth practice blocked even after six hours');
assert(!p(records([0,6,12].map(h=>h*3600000)),PRACTICE_DAY_MS-1000).allowed,'fourth practice still blocked before 24 hours');
assert(p(records([0,6,12].map(h=>h*3600000)),PRACTICE_DAY_MS).allowed,'first slot expires at 24 hours');
assert.equal(p(records([0,6,12].map(h=>h*3600000)),23*3600000).recentCount,3);
assert(!t([],[],0).allowed,'zero completed modules');
assert(!t([],modules.slice(0,1),0).allowed,'only one completed module');
assert(t([],modules,0).allowed,'two distinct completed modules');
assert.equal(t([],modules.concat({module:'daily:1',completed_at:iso(-4000)}),0).modulesCompleted,2,'duplicate completion cannot inflate module count');
assert(!t(records([0],'test'),modules,TEST_INTERVAL_MS-1000).allowed,'test at six days 23h must be blocked');
assert(t(records([0],'test'),modules.map(m=>({...m,completed_at:iso(TEST_INTERVAL_MS-1000)})),TEST_INTERVAL_MS).allowed,'test opens after exactly seven days with fresh modules');
assert(!t([],modules,new Date(iso(TEST_INTERVAL_MS)).getTime()-base).allowed,'modules outside seven-day window no longer qualify');
assert.equal(t([],modules,0).modulesCompleted,2);
assert.equal(p(records([0]),3600000).nextAt,iso(PRACTICE_INTERVAL_MS));
console.log('PASS: 6-hour slots, 3 per rolling 24h, 7-day tests, two completed modules and boundaries');
